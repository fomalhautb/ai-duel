  'model-distillation':
    '技能牌：打出时要点自己手牌里一张 AI 牌，把它弃掉，换来等同它卡面费用 +1 的 Token。换来的 Token 可以超过本轮上限，但下一轮补满时就没了。',
  'memory-shortage':
    '技能牌：双方各随机留下场上一半 AI（单数向上取整），其余进弃牌堆。你自己的场面照清不误，谁打的都一样。',
  'domestic-substitution':
    '技能牌：双方场上没有国产标签的 AI 全部进弃牌堆，包括你自己那边的。',
